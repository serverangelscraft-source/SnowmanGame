package com.snowmangame;

/**
 * Grade-specific school content. Kept separate from the day state machine so
 * story variety can grow without touching save/progression rules.
 */
public final class SchoolGradeContent {
    private SchoolGradeContent() {}

    public static String theme(int grade){
        switch(grade){
            case 2:return "Дружба";
            case 3:return "Команда";
            case 4:return "Самостійність";
            case 5:return "Допомога молодшим";
            case 6:return "Відповідальність";
            case 7:return "Власний голос";
            case 8:return "Вибір і наслідки";
            case 9:return "Майстерність";
            case 10:return "Плани на майбутнє";
            case 11:return "Випуск і свій шлях";
            default:return "Шкільне життя";
        }
    }

    public static String dayHook(int grade,int schoolDay){
        int d=Math.max(1,Math.min(5,schoolDay));
        if(grade==7){String[] a={"Новий гурток","Суперечка в команді","Виступ перед класом","Допомога новачку","Спільне рішення"};return a[d-1];}
        if(grade==8){String[] a={"План на тиждень","Чесна домовленість","Помилка без паніки","Вибір ролі","Відповідальність за результат"};return a[d-1];}
        if(grade==9){String[] a={"Знайти свій сильний бік","Навчити іншого","Складніша задача","Мініпроєкт","Показати результат"};return a[d-1];}
        if(grade==10){String[] a={"Ким хочу стати","Що вмію вже","Командний проєкт","Реальний план","Перший крок"};return a[d-1];}
        if(grade==11){String[] a={"Останній навчальний рік","Підтримати клас","Фінальний проєкт","Лист собі в майбутнє","День перед випуском"};return a[d-1];}
        return "Шкільний день";
    }

    public static String question(int grade,int schoolDay,boolean second){
        int d=Math.max(1,Math.min(5,schoolDay));
        if(grade==7){
            String[] a={"Як сказати свою думку без сварки?","Що робити, якщо команда не згодна?","Що допомагає не боятися виступу?","Новенький стоїть сам. Що зробити?","Як прийняти спільне рішення?"};
            String[] b={"Що робимо, коли інший думає інакше?","Як перевірити, що всіх почули?","Що краще перед виступом?","Як допомогти без тиску?","Що робимо після рішення?"};return (second?b:a)[d-1];
        }
        if(grade==8){
            String[] a={"З чого почати складний тиждень?","Домовились про справу. Що важливо?","Зробив помилку. Що далі?","У команді кілька ролей. Як обрати?","Хто відповідає за твою частину роботи?"};
            String[] b={"Що робити, якщо план змінився?","Як сказати, що не встигаєш?","Що корисніше за виправдання?","Коли можна змінити роль?","Що робити після невдалого результату?"};return (second?b:a)[d-1];
        }
        if(grade==9){
            String[] a={"Як зрозуміти свій сильний бік?","Як найкраще пояснити іншому?","Що робити зі складною задачею?","З чого починається мініпроєкт?","Що важливо під час показу результату?"};
            String[] b={"Що робити з тим, що поки не виходить?","Як перевірити, що тебе зрозуміли?","Коли варто просити допомогу?","Що тримає проєкт від хаосу?","Що робити з відгуком після показу?"};return (second?b:a)[d-1];
        }
        if(grade==10){
            String[] a={"Як обрати напрям, якщо подобається кілька?","Що важливіше за красиву назву професії?","Що робить командний проєкт реальним?","Яким має бути хороший план?","Що перетворює план на дію?"};
            String[] b={"Чи можна змінити майбутній напрям?","Як помітити власний прогрес?","Що робити, коли команда відстає?","Навіщо плану запасний варіант?","Який крок найкращий першим?"};return (second?b:a)[d-1];
        }
        if(grade==11){
            String[] a={"Що важливо зберегти з останнього року?","Однокласник хвилюється. Що зробити?","Що головне у фінальному проєкті?","Що варто написати собі в майбутнє?","Що означає завершити школу?"};
            String[] b={"Що робити зі страхом перед змінами?","Як підтримати, не вирішуючи все за іншого?","Як зрозуміти, що проєкт готовий?","Що з планів можна переглянути пізніше?","Що залишається після випуску?"};return (second?b:a)[d-1];
        }
        return null;
    }

    public static String[] options(int grade,int schoolDay,boolean second){
        String q=question(grade,schoolDay,second);
        if(q==null)return null;
        if(q.contains("сварки"))return new String[]{"СПОКІЙНО ПОЯСНИТИ","ПЕРЕКРИЧАТИ","МОВЧАТИ ЗАВЖДИ"};
        if(q.contains("команда не згодна"))return new String[]{"ОБГОВОРИТИ ПРИЧИНУ","ОБРАЗИТИСЯ","ПІТИ"};
        if(q.contains("виступ"))return new String[]{"ПІДГОТУВАТИСЯ І СПРОБУВАТИ","СХОВАТИСЯ","ЗІРВАТИ УРОК"};
        if(q.contains("Новенький"))return new String[]{"ПРИВІТАТИСЯ І ЗАПРОСИТИ","ІГНОРУВАТИ","СМІЯТИСЯ"};
        if(q.contains("спільне рішення"))return new String[]{"ПОЧУТИ ВСІХ","ВИРІШИТИ САМОМУ","ПОСПЕРЕЧАТИСЯ"};
        if(q.contains("план"))return new String[]{"РОЗБИТИ НА КРОКИ","ЧЕКАТИ ВИПАДКУ","ВІДКЛАСТИ НАЗАВЖДИ"};
        if(q.contains("помил"))return new String[]{"РОЗІБРАТИ І ВИПРАВИТИ","СХОВАТИ","ЗВИНУВАТИТИ ІНШИХ"};
        if(q.contains("роль"))return new String[]{"ОБРАТИ ЗА СИЛЬНИМИ","ТЯГНУТИ ЖЕРЕБ ЗАВЖДИ","НЕ РОБИТИ НІЧОГО"};
        if(q.contains("сильн"))return new String[]{"СПРОБУВАТИ Й ПОРІВНЯТИ","ВГАДАТИ","НЕ ПРОБУВАТИ"};
        if(q.contains("поясн"))return new String[]{"ПРОСТО І З ПРИКЛАДОМ","ДУЖЕ ШВИДКО","НЕ СЛУХАТИ ПИТАНЬ"};
        if(q.contains("задач"))return new String[]{"РОЗБИТИ НА ЧАСТИНИ","КИНУТИ","ВГАДУВАТИ"};
        if(q.contains("проєкт"))return new String[]{"МЕТА І КРОКИ","ЛИШЕ НАЗВА","БЕЗ ПЛАНУ"};
        if(q.contains("профес"))return new String[]{"ЩО ТОБІ ПІДХОДИТЬ","МОДНА НАЗВА","ЧУЖИЙ ВИБІР"};
        if(q.contains("майбут"))return new String[]{"МОЖНА КОРИГУВАТИ","НЕ МОЖНА НІКОЛИ","ВИРІШУЮТЬ ІНШІ"};
        if(q.contains("підтрим"))return new String[]{"БУТИ ПОРУЧ І СЛУХАТИ","КОМАНДУВАТИ","ІГНОРУВАТИ"};
        if(q.contains("школ"))return new String[]{"ЗАВЕРШИТИ ЕТАП І ЙТИ ДАЛІ","ЗАБУТИ ВСЕ","НІЧОГО НЕ ЗМІНЮЄТЬСЯ"};
        return new String[]{"ПОДУМАТИ І ДІЯТИ","ІГНОРУВАТИ","ПЕРЕКЛАСТИ НА ІНШИХ"};
    }

    public static int correct(int grade,int schoolDay,boolean second){
        return question(grade,schoolDay,second)==null?-1:0;
    }
}
